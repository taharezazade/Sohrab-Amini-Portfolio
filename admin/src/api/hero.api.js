/** @format */

import api from "./axios.js";

const heroApi = {
  /* =======================================================
      Get Hero
  ======================================================= */

  getHero() {
    return api.get("/hero");
  },

  /* =======================================================
      Create Hero
  ======================================================= */

  createHero(data) {
    return api.post("/hero", data);
  },

  /* =======================================================
      Update Hero
  ======================================================= */

  updateHero(data) {
    return api.put("/hero", data);
  },

  /* =======================================================
      Delete Hero
  ======================================================= */

  deleteHero() {
    return api.delete("/hero");
  },
};

export default heroApi;
